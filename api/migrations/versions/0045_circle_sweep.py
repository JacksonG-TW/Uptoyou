# **«Touched» is the latest of these writes in the circle**: the circle itself, a seat joining, a
# round opening or closing, a proposal, a tap on the dice, a preference, a place the circle named
# itself (D28's circle-local), a link minted or replaced. **Not a device secret**: one is minted with
# a seat, which `joined_at` already counts, and a secret belongs to a principal who may sit in other
# circles. `greatest` ignores nulls, so a circle with no rounds is judged on what it does have.
CANDIDATES_SQL = """
create function public.circle_sweep_candidates()
returns table (circle_id bigint, last_touch timestamptz)
language sql
stable
security definer
set search_path = pg_catalog, pg_temp
as $body$
    select touched.id, touched.last_touch
      from (
        select c.id,
               c.self_serve,
               greatest(
                   c.created_at,
                   (select max(m.joined_at) from public.member m where m.circle_id = c.id),
                   (select max(greatest(r.opened_at, r.closed_at))
                      from public.round r where r.circle_id = c.id),
                   (select max(p.proposed_at) from public.proposal p
                      join public.round r on r.id = p.round_id where r.circle_id = c.id),
                   (select max(mr.rolled_at) from public.member_roll mr where mr.circle_id = c.id),
                   (select max(pr.recorded_at) from public.preference pr
                      join public.member m on m.id = pr.member_id where m.circle_id = c.id),
                   (select max(pl.created_at) from public.place pl where pl.circle_id = c.id),
                   (select max(greatest(j.created_at, j.revoked_at))
                      from public.join_ticket j where j.circle_id = c.id)
               ) as last_touch
          from public.circle c
      ) as touched
     where touched.self_serve
       and not exists (select 1 from public.trip t where t.circle_id = touched.id)
       and touched.last_touch < now() - interval '{window}'
     order by touched.id
$body$
""".format(window=IDLE_WINDOW)


# **The order is the foreign-key graph, children first, and it is written out on purpose** (H98).
# Every step counts in a dry run and deletes otherwise, over the same predicate, so the two modes
# cannot report different sets.
#
# * `weight_contribution` first: it pins `preference` and `trip` with RESTRICT (D24, D114).
# * `trip` is never deleted: the candidate rule excludes any circle that has one, and
#   `trip → round` staying NO ACTION means a mistaken selection fails at `round` instead of
#   deleting a signed trip.
# * A **principal** goes only if this circle held its last seat. A principal can sit in several
#   circles (D74, `upto.issue --principal`), and its `device_secret` is per principal, so deleting
#   the secret of a principal who sits elsewhere would lock that person out of a circle the sweep
#   never selected.
SWEEP_SQL = """
create function public.sweep_circle(p_circle bigint, p_dry_run boolean default false)
returns table (step text, rows_affected bigint)
language plpgsql
volatile
security definer
set search_path = pg_catalog, pg_temp
set lock_timeout = '{lock_timeout}'
as $body$
declare
    n bigint;
    last_seat bigint[];
begin
    -- **Lock every row a new write would point at, THEN re-check, then delete.** Locking only the
    -- circle is not enough (the reviewer's pre-read, 2026-09-14): a proposal, a roll or a
    -- preference points at `round` or `member`, not at `circle`, so it would not wait on that
    -- lock — and under READ COMMITTED each DELETE below takes a fresh snapshot, so a proposal
    -- committed between the re-check and the proposal delete would be swept with the circle,
    -- seconds after a member acted. `for update` conflicts with the `for key share` every
    -- referencing insert takes, so from here on each such insert waits for this transaction and
    -- then fails its foreign key; one that committed before the locks were granted is seen by the
    -- re-check and makes the circle touched.
    --
    -- **The lock order is circle → round → member → proposal, and it is the product's order.**
    -- Joining a circle locks the circle first (`grow_seat`); a roll updates the round and then
    -- inserts rows pointing at member and proposal (`rounds.py`, `engine/store.py`); nothing in
    -- the API locks a round or a member and then the circle. The one path that can still form a
    -- cycle is a single INSERT whose foreign-key checks take their shares in trigger order (a
    -- proposal or a trip). **So this function waits at most `lock_timeout` for any lock, below
    -- the server's `deadlock_timeout` (1 s, measured), and the inequality is not the whole reason**
    -- (the reviewer's third pre-read): PostgreSQL runs the deadlock check `deadlock_timeout` after
    -- EACH backend began waiting, and in a cycle the member began first. The sweep still yields
    -- first because it requests its next lock within milliseconds of being granted the one the
    -- member is waiting on, so its own wait starts almost when the member's does and ends half a
    -- second later, while the member's check is due a full second after its start. The server
    -- setting is not pinned by this function; `test_circle_sweep_integration` asserts
    -- `lock_timeout < deadlock_timeout` so a lowered server setting turns a test red.
    --
    -- **The re-check is its own statement, after the locks** (the reviewer's second pre-read): a
    -- locking read that waited re-reads only the rows it locked, so a predicate folded into the
    -- same statement would miss a proposal committed while it waited. This function is VOLATILE
    -- so each statement below takes its own snapshot.
    perform 1 from public.circle where id = p_circle for update;
    if not found then
        raise exception 'sweep_circle: circle % does not exist', p_circle
            using errcode = 'no_data_found';
    end if;
    perform 1 from public.round where circle_id = p_circle for update;
    perform 1 from public.member where circle_id = p_circle for update;
    perform 1 from public.proposal
     where round_id in (select id from public.round where circle_id = p_circle) for update;
    if not exists (select 1 from public.circle_sweep_candidates() s where s.circle_id = p_circle) then
        raise exception 'sweep_circle: circle % is not sweepable (self-serve, never a signed trip, '
                        'untouched for {window})', p_circle
            using errcode = 'object_not_in_prerequisite_state';
    end if;

    select coalesce(array_agg(m.principal_id), '{{}}') into last_seat
      from public.member m
     where m.circle_id = p_circle
       and not exists (select 1 from public.member o
                        where o.principal_id = m.principal_id and o.circle_id <> p_circle);

    step := 'weight_contribution';
    if p_dry_run then
        select count(*) into n from public.weight_contribution
         where round_id in (select id from public.round where circle_id = p_circle);
    else
        delete from public.weight_contribution
         where round_id in (select id from public.round where circle_id = p_circle);
        get diagnostics n = row_count;
    end if;
    rows_affected := n; return next;

    step := 'round_forecast_baseline';
    if p_dry_run then
        select count(*) into n from public.round_forecast_baseline
         where round_id in (select id from public.round where circle_id = p_circle);
    else
        delete from public.round_forecast_baseline
         where round_id in (select id from public.round where circle_id = p_circle);
        get diagnostics n = row_count;
    end if;
    rows_affected := n; return next;

    step := 'member_roll';
    if p_dry_run then
        select count(*) into n from public.member_roll where circle_id = p_circle;
    else
        delete from public.member_roll where circle_id = p_circle;
        get diagnostics n = row_count;
    end if;
    rows_affected := n; return next;

    step := 'proposal';
    if p_dry_run then
        select count(*) into n from public.proposal
         where round_id in (select id from public.round where circle_id = p_circle);
    else
        delete from public.proposal
         where round_id in (select id from public.round where circle_id = p_circle);
        get diagnostics n = row_count;
    end if;
    rows_affected := n; return next;

    step := 'preference';
    if p_dry_run then
        select count(*) into n from public.preference
         where member_id in (select id from public.member where circle_id = p_circle);
    else
        delete from public.preference
         where member_id in (select id from public.member where circle_id = p_circle);
        get diagnostics n = row_count;
    end if;
    rows_affected := n; return next;

    step := 'round';
    if p_dry_run then
        select count(*) into n from public.round where circle_id = p_circle;
    else
        delete from public.round where circle_id = p_circle;
        get diagnostics n = row_count;
    end if;
    rows_affected := n; return next;

    step := 'device_secret';
    if p_dry_run then
        select count(*) into n from public.device_secret where principal_id = any (last_seat);
    else
        delete from public.device_secret where principal_id = any (last_seat);
        get diagnostics n = row_count;
    end if;
    rows_affected := n; return next;

    step := 'member';
    if p_dry_run then
        select count(*) into n from public.member where circle_id = p_circle;
    else
        delete from public.member where circle_id = p_circle;
        get diagnostics n = row_count;
    end if;
    rows_affected := n; return next;

    step := 'principal';
    if p_dry_run then
        select count(*) into n from public.principal where id = any (last_seat);
    else
        delete from public.principal where id = any (last_seat);
        get diagnostics n = row_count;
    end if;
    rows_affected := n; return next;

    step := 'join_ticket';
    if p_dry_run then
        select count(*) into n from public.join_ticket where circle_id = p_circle;
    else
        delete from public.join_ticket where circle_id = p_circle;
        get diagnostics n = row_count;
    end if;
    rows_affected := n; return next;

    step := 'place';
    if p_dry_run then
        select count(*) into n from public.place where circle_id = p_circle;
    else
        delete from public.place where circle_id = p_circle;
        get diagnostics n = row_count;
    end if;
    rows_affected := n; return next;

    step := 'circle';
    if p_dry_run then
        n := 1;
    else
        delete from public.circle where id = p_circle;
        get diagnostics n = row_count;
    end if;
    rows_affected := n; return next;
end
$body$
""".format(window=IDLE_WINDOW, lock_timeout=LOCK_TIMEOUT)


def upgrade() -> None:
    # Existing rows are false by the default, which is the ruling: nothing made before this
    # revision came through the self-serve door as far as the database can tell, and a circle the
    # sweep cannot prove is self-serve is never swept.
    op.add_column(
        "circle",
        sa.Column("self_serve", sa.Boolean, nullable=False, server_default=sa.false()),
    )
    # Idempotent, and `nologin` re-asserted on every run: the role is cluster-wide, so it may
    # already exist from another database, and a role this revision relies on being unable to log
    # in must be unable to log in whatever state it was found in.
    op.execute(sa.text(
        "do $role$ begin "
        "if not exists (select 1 from pg_roles where rolname = '{0}') then "
        'create role "{0}" nologin; '
        "end if; end $role$".format(SWEEPER)))
    op.execute(sa.text('alter role "{}" nologin'.format(SWEEPER)))
    for table in SWEEPER_DELETES:
        op.execute(sa.text('grant select, delete on public."{}" to "{}"'.format(table, SWEEPER)))
    for table in SWEEPER_READS_ONLY:
        op.execute(sa.text('grant select on public."{}" to "{}"'.format(table, SWEEPER)))
    for table in SWEEPER_LOCKS:
        op.execute(sa.text('grant update (id) on public."{}" to "{}"'.format(table, SWEEPER)))

    op.execute(sa.text(CANDIDATES_SQL))
    op.execute(sa.text(SWEEP_SQL))
    erasure = _erasure_role()
    for signature in (CANDIDATES, SWEEP):
        op.execute(sa.text('alter function {} owner to "{}"'.format(signature, SWEEPER)))
        op.execute(sa.text("revoke all on function {} from public".format(signature)))
        op.execute(sa.text('grant execute on function {} to "{}"'.format(signature, erasure)))


def downgrade() -> None:
    op.execute(sa.text("drop function {}".format(SWEEP)))
    op.execute(sa.text("drop function {}".format(CANDIDATES)))
    for table in SWEEPER_DELETES + SWEEPER_READS_ONLY:
        op.execute(sa.text('revoke all on public."{}" from "{}"'.format(table, SWEEPER)))
    op.drop_column("circle", "self_serve")
